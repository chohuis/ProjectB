"use strict";
/**
 * **헤드리스 동시 실행 안전선** — 실측으로 정한 값 (2026-09-09 · 계측 2-2).
 *
 * ── 실측 (12코어·64GB · 한 판 1시즌 · `npm run probe:a:concurrency`) ──
 *
 * ```
 *   동시  벽시계  성공   판당 중앙   순차 대비   처리량
 *    1     202초  1/1      202초      ×1.00     3.36분/판
 *    2     184초  2/2      184초      ×0.91     1.54분/판
 *    4     225초  4/4      223초      ×1.10     0.94분/판
 *    6     233초  6/6      232초      ×1.15     0.65분/판
 *    8     289초  8/8      284초      ×1.41     0.60분/판
 * ```
 *
 * 🔴 **여덟까지 한 판도 안 죽었다.** 「예전에 8병렬로 돌려 전부 타임아웃」은
 *   동시 실행의 한계가 아니었다 — 그때는 **여러 스크립트를 같이** 돌려 실효
 *   동시 수가 8 을 넘었고, **타임아웃이 순차 기준으로 잡혀 있었다.**
 *   판당 시간이 ×1.4 로 늘면 순차 기준 상한은 당연히 걸린다.
 *
 * ── 안전선을 **6** 으로 잡은 이유 ──────────────────────────────
 *   · 6 까지는 판당 시간이 ×1.15 안이다. 8 은 ×1.41 이라 **상한을 같이 늘려야**
 *     한다 — 상한을 안 늘리면 그때 죽는다(그게 예전에 난 일이다).
 *   · 처리량은 6 → 8 에서 0.65 → 0.60 분/판, **8% 밖에 안 는다.**
 *     판당 시간을 22% 더 주고 얻는 값이 아니다.
 *   · 남는 코어 여섯은 vitest·tsc·빌드가 쓴다. 계측이 기계를 다 먹으면
 *     다른 세션이 멈춘다(그 사고가 있었다).
 *
 * ⚠ **1시즌 판으로 잰 값이다.** 12시즌 판은 메모리가 더 오래 붙어 있으므로
 *   8 로 올리기 전에 **그 길이로 다시 재라.** 재는 계기는 그대로 있다.
 * ⚠ **상한은 동시 수에 따라 늘려라** — `timeoutFor(n)` 가 그 배수를 준다.
 * ⚠ 앱(전자 창)은 따로다 — 규칙의 「electron 동시 셋까지」는 화면이 뜨는 쪽이고
 *   여기는 헤드리스(`ELECTRON_RUN_AS_NODE`)다.
 */

/** 헤드리스 판을 동시에 몇 개까지 — 실측 안전선 */
const SAFE_CONCURRENCY = 6;

/**
 * 동시 `n` 판일 때 한 판에 줄 상한.
 *
 * 판당 시간이 동시 수에 따라 늘어난다(실측 ×1.00 → ×1.41). 순차 기준 상한을
 * 그대로 쓰면 **동시에 돌린다는 이유만으로** 죽는다 — 예전에 그렇게 났다.
 */
function timeoutFor(baseMs, n) {
  const factor = n <= 1 ? 1.0 : n <= 2 ? 1.0 : n <= 4 ? 1.2 : n <= 6 ? 1.3 : 1.6;
  // 여유를 더 둔다 — 상한은 「진짜로 멈춘 것」을 잡는 자이지 빠듯하게 잴 자가 아니다
  return Math.round(baseMs * factor * 1.5);
}

/**
 * 일감 목록을 동시 `limit` 개씩 돌린다. 순서는 안 보장하고 **결과는 입력 순서**다.
 *
 * ⚠ `Promise.all` 로 통째로 띄우지 않는다 — 스무 판이면 스무 개가 한꺼번에 뜬다.
 */
async function runPool(items, limit, worker) {
  const out = new Array(items.length);
  let next = 0;
  const lanes = Array.from({ length: Math.max(1, Math.min(limit, items.length)) }, async () => {
    for (;;) {
      const i = next++;
      if (i >= items.length) return;
      out[i] = await worker(items[i], i);
    }
  });
  await Promise.all(lanes);
  return out;
}

module.exports = { SAFE_CONCURRENCY, timeoutFor, runPool };
